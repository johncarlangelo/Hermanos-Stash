/**
 * Regenerates docs/workflow-audit/COMPATIBILITY_MATRIX.md from the verified CSV
 * exports. Run `npm run workflow:matrix` after adding or altering any tool.
 *
 * The CSVs are produced by workflow.test.ts only when
 * STASH_EXPORT_COMPATIBILITY=1, and every exported row is asserted against the
 * production validator in the same run. This script therefore never invents
 * data: it fails loudly if the CSVs are missing or stale-shaped, and it renders
 * them deterministically (no timestamps) so diffs stay meaningful.
 */
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const auditDir = join(root, 'docs', 'workflow-audit')
const staging = mkdtempSync(join(tmpdir(), 'stash-matrix-'))
process.on('exit', () => rmSync(staging, { recursive: true, force: true }))
const checkOnly = process.argv.includes('--check')
const csvPath = join(staging, 'compatibility.csv')
const toolsCsvPath = join(staging, 'tools.csv')
const docPath = join(auditDir, 'COMPATIBILITY_MATRIX.md')

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let inQuotes = false
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else inQuotes = false
      } else field += ch
    } else if (ch === '"') inQuotes = true
    else if (ch === ',') {
      row.push(field)
      field = ''
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++
      row.push(field)
      field = ''
      if (row.some((f) => f !== '')) rows.push(row)
      row = []
    } else field += ch
  }
  if (field !== '' || row.length > 0) {
    row.push(field)
    if (row.some((f) => f !== '')) rows.push(row)
  }
  return rows
}

function readCsv(path, expectedHeader, expectedRows) {
  const rows = parseCsv(readFileSync(path, 'utf8'))
  const header = rows[0]
  if (header.join(',') !== expectedHeader) {
    throw new Error(`${path}: expected header "${expectedHeader}", got "${header.join(',')}"`)
  }
  const records = rows.slice(1).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])))
  if (expectedRows !== undefined && records.length !== expectedRows) {
    throw new Error(
      `${path}: expected ${expectedRows} rows, got ${records.length}. Regenerate the CSVs first.`
    )
  }
  return records
}

// 1. Refresh the verified CSV exports (the test asserts every row against the
//    independent audit oracle, so a failing suite aborts the doc regeneration).
const test = spawnSync(
  process.execPath,
  [
    join(root, 'node_modules/vitest/vitest.mjs'),
    'run',
    'src/renderer/features/workflow/workflow.test.ts'
  ],
  {
    cwd: root,
    env: {
      ...process.env,
      STASH_EXPORT_COMPATIBILITY: '1',
      STASH_COMPATIBILITY_OUTPUT_DIR: staging
    },
    encoding: 'utf8',
    timeout: 120000
  }
)
if (test.status !== 0) {
  console.error(test.stdout)
  console.error(test.stderr)
  throw new Error('Compatibility tests failed; refusing to regenerate the matrix document.')
}

const tools = readCsv(toolsCsvPath, 'id,input,output,acceptsText,producesText')
const pairs = readCsv(csvPath, 'from,to,files,text,fileReason,textReason', tools.length ** 2)

const bySource = new Map()
for (const pair of pairs) {
  if (!bySource.has(pair.from)) bySource.set(pair.from, [])
  bySource.get(pair.from).push(pair)
}
const toolById = new Map(tools.map((t) => [t.id, t]))

// Domain-transition counts for the summary grid (file port only).
const domainTransitions = new Map()
for (const pair of pairs) {
  if (pair.files !== 'true') continue
  const out = toolById.get(pair.from).output
  const inp = toolById.get(pair.to).input
  const key = `${out}->${inp}`
  domainTransitions.set(key, (domainTransitions.get(key) ?? 0) + 1)
}
const domains = [...new Set(tools.flatMap((t) => [t.input, t.output]).filter((d) => d !== '-'))]

function md(value) {
  return String(value).replaceAll('|', '&#124;').replaceAll('\n', '<br>')
}

const lines = []
lines.push('<!-- GENERATED by scripts/generate-compatibility-doc.mjs — do not edit by hand.')
lines.push(
  '     Regenerate with `npm run workflow:matrix` (runs the verifying test suite first). -->'
)
lines.push('')
lines.push('# Queue Workflow Compatibility Matrix')
lines.push('')
lines.push(
  `**Workflow feature version:** \`${(readFileSync(join(root, 'src/renderer/features/workflow/version.ts'), 'utf8').match(/'([^']+)'/) ?? [])[1] ?? 'unknown'}\` · **Registered tools:** ${tools.length} · **Ordered tool pairs:** ${pairs.length} · **Port combinations per pair:** 4 (files→files, text→text, files→text, text→files) · **Total documented combinations:** ${pairs.length * 4}`
)
lines.push('')
lines.push(
  '**Source of truth:** the committed CSVs in this folder, which are written only by `workflow.test.ts` after asserting every row against the independent audit fixture (`compatibility-audit.ts`). This document is a human-readable rendering of those CSVs; the CSVs remain the pair-level record.'
)
lines.push('')
lines.push(
  '> Compatibility is media-domain-level. Same-domain connections can still differ by codec/extension (SVG, GIF, ICO, audio formats), and text wires do not validate content (JSON, SQL, …). Mixed-output producers are classified conservatively until the user selects an artifact type. Execution itself is simulated; this matrix says nothing about real processor runs. Full limitations: [README.md](./README.md).'
)
lines.push('')
lines.push('## How the 4 port combinations per pair resolve')
lines.push('')
lines.push('| Combination | Result |')
lines.push('| --- | --- |')
lines.push(
  `| files → text, text → files | Always REJECT (mismatched ports) — ${pairs.length} pairs × 2 = ${pairs.length * 2} combinations |`
)
lines.push(
  `| files → files | Valid for ${pairs.filter((p) => p.files === 'true').length} pairs; rejected for ${pairs.filter((p) => p.files !== 'true').length} with a media-domain reason |`
)
lines.push(
  `| text → text | Valid for ${pairs.filter((p) => p.text === 'true').length} pairs; rejected when either side lacks text ports |`
)
lines.push('')
lines.push('## Domain transition summary (file port)')
lines.push('')
lines.push(
  'Allowed file-wire counts by output domain of the source → input domain of the destination. Universal consumers accept any classified output; unknown/mixed outputs only feed universal consumers.'
)
lines.push('')
lines.push(`| out \\ in | ${domains.join(' | ')} |`)
lines.push(`| --- | ${domains.map(() => '---').join(' | ')} |`)
for (const out of domains) {
  const cells = domains.map((inp) => String(domainTransitions.get(`${out}->${inp}`) ?? 0))
  lines.push(`| ${out} | ${cells.join(' | ')} |`)
}
lines.push('')
lines.push('## Tool inventory')
lines.push('')
lines.push('| Tool | File input | File output | Text in | Text out |')
lines.push('| --- | --- | --- | --- | --- |')
for (const t of tools) {
  lines.push(`| \`${t.id}\` | ${t.input} | ${t.output} | ${t.acceptsText} | ${t.producesText} |`)
}
lines.push('')
lines.push('## Per-source wiring reference')
lines.push('')
lines.push(
  'Each source section lists every destination and all four port verdicts. Self-tool pairs mean distinct nodes; self-node wires and cycles are rejected separately. Reasons are reported separately for each same-type port.'
)
lines.push('')
for (const t of tools) {
  lines.push(
    `### ${t.id}`,
    '',
    '| Destination | files → files | text → text | files → text | text → files | File reason | Text reason |',
    '| --- | --- | --- | --- | --- | --- | --- |'
  )
  for (const r of bySource.get(t.id)) {
    lines.push(
      `| ${md(r.to)} | ${r.files === 'true' ? 'ALLOW' : 'REJECT'} | ${r.text === 'true' ? 'ALLOW' : 'REJECT'} | REJECT | REJECT | ${md(r.fileReason)} | ${md(r.textReason)} |`
    )
  }
  lines.push('')
}

const next = lines.join('\n')
const outputs = new Map([
  [docPath, next],
  [join(auditDir, 'tools.csv'), readFileSync(toolsCsvPath, 'utf8')],
  [join(auditDir, 'compatibility.csv'), readFileSync(csvPath, 'utf8')]
])
let changed = 0
for (const [file, content] of outputs) {
  let previous = null
  try {
    previous = readFileSync(file, 'utf8').replaceAll('\r\n', '\n')
  } catch {
    /* Missing artifact is stale. */
  }
  if (previous !== content) {
    changed++
    if (checkOnly) console.error(`Stale artifact: ${file}. Run npm run workflow:matrix`)
    else writeFileSync(file, content)
  }
}
console.log(
  JSON.stringify({
    tools: tools.length,
    pairs: pairs.length,
    combinations: pairs.length * 4,
    changed,
    checkOnly
  })
)
if (checkOnly && changed) process.exitCode = 1
